CREATE STAGE IF NOT EXISTS MP_STAGE;
CREATE TABLE IF NOT EXISTS MP_LOAD_BATCHES (
 BATCH_ID VARCHAR NOT NULL, RUN_ID VARCHAR NOT NULL, ROW_COUNT NUMBER NOT NULL,
 LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS MP_FACT_BARS (
 RUN_ID VARCHAR NOT NULL, EVENT_ID VARCHAR NOT NULL, SYMBOL VARCHAR NOT NULL,
 EVENT_TIME TIMESTAMP_TZ NOT NULL, OPEN NUMBER(28,12),HIGH NUMBER(28,12),LOW NUMBER(28,12),
 CLOSE NUMBER(28,12),VOLUME NUMBER(28,12),CURRENCY VARCHAR,PROVIDER VARCHAR,PAYLOAD_HASH VARCHAR,SOURCE_MODE VARCHAR,
 LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
